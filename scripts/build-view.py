#!/usr/bin/env python3
"""Build a UI pack's pack viewer (<pack>/view/index.html). It works when the file is opened directly in a browser (file URL).

Usage:
  python3 build-view.py <pack folder> [--work work-folder]

What it does:
  1. Copies the skill's viewer/ template into a work folder (default: a temporary folder) and installs its dependencies.
  2. Installs the pack into that app with install.py and uses the pack's layout example as the layout.
  3. Wires the gallery and the theme switch component from the `viewer` entry of pack.json, and adds pack.json,
     the design guide and the list of reference patterns.
  4. Puts the CSS, fonts and scripts of the next build (static export) into one index.html and writes it to
     <pack>/view/index.html. It reads no other file, so the components render and work when the file is opened
     directly in any browser.
  5. Captures the gallery part in the light and dark theme with Chrome as view/preview-*.png, and rebuilds the
     pack index (packs/index.html).
The pack's own files are not changed. Only <pack>/view/ is recreated.
"""
import argparse, base64, json, pathlib, re, shutil, subprocess, sys, tempfile

HERE = pathlib.Path(__file__).resolve().parent
SKILL = HERE.parent

ap = argparse.ArgumentParser()
ap.add_argument("pack")
ap.add_argument("--work", default=None, help="folder to build in (must not exist). Default: a temporary folder")
a = ap.parse_args()

pack = pathlib.Path(a.pack).expanduser().resolve()
meta = json.loads((pack / "pack.json").read_text())
viewer = meta.get("viewer")
if not viewer or "gallery" not in viewer:
    sys.exit('pack.json has no viewer.gallery. Example: "viewer": {"gallery": "@/components/design/Gallery#Gallery"}')

work = pathlib.Path(a.work).expanduser().resolve() if a.work else pathlib.Path(tempfile.mkdtemp(prefix=f"ui-pack-view-{meta['name']}-"))
app = work / "app"
if app.exists():
    sys.exit(f"The work folder already exists: {app}")

def run(cmd, cwd):
    print("$", " ".join(cmd), flush=True)
    subprocess.run(cmd, cwd=cwd, check=True)

# 1. Template and dependencies
shutil.copytree(SKILL / "viewer", app)
run(["pnpm", "install", "--silent"], app)

# 2. Install the pack (with its dependencies). The gallery route (/design) is not needed in the viewer and is removed.
run([sys.executable, str(HERE / "install.py"), str(pack), str(app), "--name", meta["name"]], app)
for extra in ("src/app/design", "tests", "docs", "vitest.config.mts"):
    p = app / extra
    if p.is_dir():
        shutil.rmtree(p)
    elif p.exists():
        p.unlink()
layout_src = next((e["from"] for e in meta["install"] if e["mode"] == "merge" and e["to"].endswith("app/layout.tsx")), None)
if layout_src:
    layout = (pack / layout_src).read_text()
    # A crossorigin preload is blocked on a file URL, so next/font preload is turned off (the font still loads through CSS).
    layout = re.sub(r"localFont\(\{", "localFont({\n  preload: false,", layout)
    (app / "src/app/layout.tsx").write_text(layout)
for p in (app / "src/app").glob("layout.tsx.pack-example"):
    p.unlink()

# 3. Viewer data
def reexport(spec: str, fallback: str) -> str:
    mod, _, name = spec.partition("#")
    return f'export {{ {name or fallback} as {fallback} }} from "{mod}";'

parts = ["// Generated by build-view.py from the `viewer` entry of pack.json.", reexport(viewer["gallery"], "Gallery")]
if viewer.get("themeSwitch"):
    parts.append(reexport(viewer["themeSwitch"], "ThemeSwitch"))
else:
    parts.append("export function ThemeSwitch() { return null; }")
(app / "src/app/viewer-parts.tsx").write_text("\n".join(parts) + "\n")

data = app / "src/viewer-data"
data.mkdir(parents=True)
shutil.copy2(pack / "pack.json", data / "pack.json")
guide = viewer.get("guide")
if guide:
    shutil.copy2(pack / guide, data / "guide.md")
if (SKILL / "catalog.json").exists():
    shutil.copy2(SKILL / "catalog.json", data / "catalog.json")
if (pack / "patterns").is_dir():
    files = sorted(f"patterns/{p.name}" for p in (pack / "patterns").iterdir() if p.is_file())
    (data / "patterns.json").write_text(json.dumps(files, ensure_ascii=False))

# 4. Build and convert to relative paths
run(["pnpm", "exec", "next", "build"], app)
out = app / "out"
CUR = '"object"==typeof document?document.currentScript:void 0'


def inline_fonts(css: str, css_path: pathlib.Path) -> str:
    def rep(m):
        ref = m.group(1).strip("'\"")
        f = out / ref.lstrip("/") if ref.startswith("/") else (css_path.parent / ref).resolve()
        kind = "woff2" if f.suffix == ".woff2" else f.suffix.lstrip(".")
        return f"url(data:font/{kind};base64,{base64.b64encode(f.read_bytes()).decode()})"
    return re.sub(r"url\(([^)]+\.(?:woff2|woff|ttf|otf)['\"]?)\)", rep, css)


def safe(body: str, tag: str) -> str:
    return body.replace(f"</{tag}", f"<\\/{tag}")


# Browsers differ in how far they block reading sibling files on a file URL, so the CSS, fonts and scripts all go into the one index.html.
html = (out / "index.html").read_text()

# CSS: the same content goes in as <style> and the <link> stays (React tries to re-insert the link when it cannot find it. The missing file does not affect the page).
def css_tag(m):
    f = out / m.group(1).lstrip("/")
    return f"<style>{safe(inline_fonts(f.read_text(), f), 'style')}</style>" + m.group(0)
html = re.sub(r'<link rel="stylesheet" href="([^"]+)"[^>]*/>', css_tag, html)

# Scripts: a Turbopack chunk finds its own path from the src of document.currentScript, so when it is inlined that spot is replaced with the path string.
# The runtime (turbopack-*.js) goes last so it runs after every chunk is registered (run earlier, it would try to load missing chunks as files).
chunks = out / "_next" / "static" / "chunks"
runtime: list[str] = []
used = set(re.findall(r'<script[^>]*?\ssrc="[^"]*/_next/(static/chunks/[^"]+)"', html))

def chunk_body(f: pathlib.Path) -> str:
    return safe(f.read_text().replace(CUR, json.dumps(f"static/chunks/{f.name}")), "script")

def js_tag(m):
    src = m.group(2)
    f = out / src.lstrip("/")
    attrs = re.sub(r'\s(async|crossorigin)(="[^"]*")?', "", m.group(1) + m.group(3))
    tag = f"<script{attrs}>{chunk_body(f)}</script>"
    if f.name.startswith("turbopack-"):
        runtime.append(tag)
        return ""
    return tag
html = re.sub(r'<script([^>]*?)\ssrc="([^"]+)"([^>]*)></script>', js_tag, html)
extra = "".join(f"<script>{chunk_body(f)}</script>" for f in sorted(chunks.glob("*.js")) if f"static/chunks/{f.name}" not in used)
html = html.replace("</head>", extra + "</head>", 1)
html = html.replace("</body>", "".join(runtime) + "</body>", 1)
# The remaining paths (the runtime's chunk base path, chunk paths inside the page data) become paths relative to index.html. Every path string must have the same form to be recognized as a registered chunk.
html = html.replace("/_next/", "./_next/")
html = re.sub(r'<link rel="(?:preload|icon)"[^>]*/>', "", html)
if re.search(r'<script[^>]*\ssrc=', html):
    sys.exit("A <script src> that could not be inlined is left")

view = pack / "view"
if view.exists():
    shutil.rmtree(view)
view.mkdir()
(view / "index.html").write_text(html)

# 5. Preview images (used by the pack index). Skipped when Chrome is missing.
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
previews = []
if pathlib.Path(CHROME).exists():
    for scheme, name in ((1, "preview-light.png"), (0, "preview-dark.png")):
        subprocess.run([CHROME, "--headless=new", "--hide-scrollbars", "--force-prefers-reduced-motion",
                        f"--blink-settings=preferredColorScheme={scheme}", "--virtual-time-budget=8000",
                        "--window-size=1440,1000", f"--screenshot={view / name}",
                        (view / "index.html").as_uri() + "#gallery"], capture_output=True)
        if (view / name).exists():
            previews.append(name)
else:
    print("Chrome not found; skipping the preview images")

# 6. Pack index page (packs/index.html)
def esc(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")

cards = []
for pj in sorted(pack.parent.glob("*/pack.json")):
    m = json.loads(pj.read_text())
    d = pj.parent.name
    has_view = (pj.parent / "view" / "index.html").exists()
    imgs = "".join(
        f'<img src="{esc(d)}/view/{n}" alt="{esc(m["name"])} gallery, {"light" if "light" in n else "dark"} theme" loading="lazy">'
        for n in ("preview-light.png", "preview-dark.png") if (pj.parent / "view" / n).exists()
    )
    title = esc(m["name"])
    body = f'<div class="shots">{imgs}</div>' if imgs else ""
    inner = f'{body}<p class="n">{title} <span>{esc(m["version"])}</span></p><p>{esc(m["description"])}</p>'
    cards.append(f'<li><a href="{esc(d)}/view/index.html">{inner}</a></li>' if has_view else f"<li>{inner}<p>(no pack viewer)</p></li>")
# Component × pack table: for every component defined in the skill's catalog.json, each pack's status (pack.json `components`)
matrix = ""
if (SKILL / "catalog.json").exists():
    cat = json.loads((SKILL / "catalog.json").read_text())
    metas = [(pj.parent.name, json.loads(pj.read_text())) for pj in sorted(pack.parent.glob("*/pack.json"))]
    head = "".join(f'<th scope="col">{esc(m["name"])}</th>' for _, m in metas)
    body = []
    for c in cat["categories"]:
        body.append(f'<tr><th scope="rowgroup" colspan="{len(metas) + 1}" class="g">{esc(c["name"])}</th></tr>')
        for it in c["items"]:
            cells = "".join(f'<td data-s="{esc(s)}">{esc(s)}</td>' for s in
                            (m.get("components", {}).get(it["id"], {}).get("status", "absent") for _, m in metas))
            body.append(f'<tr><th scope="row" title="{esc(it["desc"])}">{esc(it["name"])}</th>{cells}</tr>')
    legend = " · ".join(f"<b>{esc(k)}</b> {esc(v)}" for k, v in cat["statuses"].items())
    matrix = f"""<h2>Component catalog</h2>
<p class="lead">The {sum(len(c["items"]) for c in cat["categories"])} components a UI pack is expected to cover, and each pack's status. {legend}</p>
<table class="m"><thead><tr><th scope="col">Component</th>{head}</tr></thead><tbody>
{chr(10).join(body)}
</tbody></table>"""

(pack.parent / "index.html").write_text(f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>UI packs</title>
<style>
:root{{color-scheme:light dark}}
body{{font-family:system-ui,-apple-system,"Apple SD Gothic Neo",sans-serif;max-width:1200px;margin:0 auto;padding:40px 24px;line-height:1.6}}
h1{{font-size:28px;margin:0 0 4px}} .lead{{opacity:.72;margin:0 0 32px}}
ul{{list-style:none;padding:0;margin:0;display:grid;gap:32px}}
li a{{display:block;color:inherit;text-decoration:none}}
li a:hover .n{{text-decoration:underline;text-underline-offset:4px}}
.shots{{display:grid;grid-template-columns:1fr 1fr;gap:12px;margin-bottom:12px}}
.shots img{{width:100%;aspect-ratio:1440/1000;object-fit:cover;object-position:top;border-radius:8px;border:1px solid color-mix(in oklab,currentColor 16%,transparent)}}
li p{{margin:0}} .n{{font-size:18px;font-weight:600}} .n span{{font-weight:400;opacity:.6;font-size:14px}}
h2{{font-size:22px;margin:48px 0 4px}}
table.m{{border-collapse:collapse;font-size:14px;min-width:420px}}
.m th,.m td{{text-align:left;padding:5px 16px 5px 0;border-bottom:1px solid color-mix(in oklab,currentColor 14%,transparent)}}
.m th[scope=row]{{font-weight:400}} .m th.g{{padding-top:20px;font-weight:700}}
.m td[data-s="present"]{{font-weight:700}} .m td[data-s="unused"]{{text-decoration:line-through}} .m td[data-s="rules-only"]{{font-style:italic}}
</style></head><body>
<h1>UI packs</h1>
<p class="lead">Open a pack to see its live component gallery (you can click and move things), its design guide and its install details. Apply one with <code>/ui-pack apply &lt;pack&gt;</code>.</p>
<ul>
{chr(10).join(cards)}
</ul>
{matrix}
</body></html>
""")

size = sum(f.stat().st_size for f in view.rglob("*") if f.is_file())
print(f"\nPack viewer: {view / 'index.html'}  ({size / 1024 / 1024:.1f}MB, {len(previews)} preview images)")
print(f"Pack index: {pack.parent / 'index.html'}")
print(f"Build folder: {app}  (safe to delete after checking)")
